#!/usr/bin/env python3
"""Lint the plugin's instruction surface (skills/, CLAUDE.md, README.md).

The 2026-07-03 system review found that 5 700 lines of SKILL.md had zero
validation — which is how a removed third-lens role kept shipping in generator
templates, three releases of work became unreachable by routing, and four
releases went out without CHANGELOG entries. This lint makes that whole drift
class impossible to reintroduce silently.

ERRORS (exit 1, CI-blocking):
  E1  SKILL.md frontmatter parses, `name` matches its directory, `description` present
  E2  cross-references resolve: `superpowers-gstack:<skill>` names and repo
      `scripts/<file>` paths mentioned in instruction files actually exist
  E3  routing coverage: every skill directory is mentioned in CLAUDE.md
  E4  plugin.json version has a matching `## [X.Y.Z]` entry in CHANGELOG.md
  E5  all `gstack-multi-lens-review-vN` markers carry the same N
  E6  no `version:` field in skill frontmatter (plugin.json is the version)
  E7  denylist: patterns that must never reappear in instruction files
      (e.g. the third-lens `sensitive` role removed in 2.18.0)
  E8  emitted blocks are single-sourced: every shared block file in
      skills/adapt/blocks/ exists, carries its version marker on the H2
      heading line, and is in the BLOCKS roster of scripts/adapt-claude-md.py
      (the one generator since 3.1.0); adapt/SKILL.md carries no inline copy
      (no marker heading, no bare block heading) and references
      PLACEHOLDERS.md. Replaced the old byte-identity drift guard in 2.33.0 —
      one source can't drift from itself.

  E10 upstream skill references resolve: every `superpowers:<name>` names a
      real Superpowers skill (roster: SUPERPOWERS_SKILLS). E2 only ever checked
      this plugin's OWN skill names, so an upstream name was unvalidated — the
      exact content the weekly auto-update job writes from release notes.

  E11 this repo's own CLAUDE.md carries a current copy of the universal blocks.
      check-plugin-version.sh exempts this repo from the /adapt nag (correctly —
      its CLAUDE.md is the SOURCE of the routing), but the exemption was wholesale,
      so the plugin prescribed discipline it never applied to itself. The region is
      generated by scripts/sync-own-claude-md.py; this fails when it goes stale.

  E12 every `{{TOKEN}}` used in a shared block has a NON-EMPTY resolution rule in
      blocks/PLACEHOLDERS.md. Without one the generators emit it verbatim into
      the project's CLAUDE.md — the exact outcome that file's preamble forbids.
      A heading alone does not count: `## `{{TOKEN}}`` with nothing under it
      documents nothing, and passed this rule until 2.48.0.

  E13 /adapt delegates every CLAUDE.md write to scripts/adapt-claude-md.py:
      the skill names the script, and carries none of the hand-surgery
      instructions the 2.x prose had (`cp CLAUDE.md`, `sed -n '<start>`, the
      Growth / Attribution check gates). Before 3.1.0 this rule pinned twenty
      sentences of that prose because a reword could silently delete a guard;
      the guards are code with tests now, and the lint only has to keep the
      model from doing the surgery itself again.

  E14 no block file carries the `emitted=` marker attribute. Generators write that
      count into a project's CLAUDE.md at emit time; stored in the source it is a
      constant that goes stale on the next edit, and the growth check would trust it.

WARNINGS (reported, exit 0):
  W1  frontmatter description over budget (target <=30 words; hard cap comes
      with the Phase-3 description rewrites)
  W2  SKILL.md body over 500 lines (bloat radar)
  W3  SUPERPOWERS_SKILLS roster disagrees with the installed Superpowers plugin
      (maintainer machines only — CI has no upstream installed, so E10's roster
      is the CI-side source of truth and this is the drift alarm for it)

Run: python3 scripts/lint-skills.py   (from the repo root or anywhere)
"""
