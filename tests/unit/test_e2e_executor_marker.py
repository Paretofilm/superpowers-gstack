@pytest.mark.parametrize("pin,why", [
    (None, "no pin at all — the common case, must be silent"),
    ("host", "explicit host — nothing to report"),
    ("garbage", "invalid pin is the runner's error to raise, not the hook's"),
])
def test_vm_hygiene_is_silent_unless_the_project_opted_in(pin, why):
    """This hook ships to every plugin user. One that talks in projects that never
    opted in is a hook people disable, taking the useful case with it."""
    with tempfile.TemporaryDirectory() as d:
        subprocess.run(["git", "init", "-q"], cwd=d, check=True)
