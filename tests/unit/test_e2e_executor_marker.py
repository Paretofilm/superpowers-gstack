# --- the shipped hook actually behaves ---------------------------------------------

@pytest.mark.parametrize("pin,why", [
    (None, "no pin at all — the common case, must be silent"),
    ("host", "explicit host — nothing to report"),
    ("garbage", "invalid pin is the runner's error to raise, not the hook's"),
])
def test_vm_hygiene_is_silent_unless_the_project_opted_in(pin, why):
    """This hook ships to every plugin user. One that talks in projects that never
    opted in is a hook people disable, taking the useful case with it."""
    with tempfile.TemporaryDirectory() as d:
        subprocess.run(["git", "init", "-q"], cwd=d, check=True)
        if pin is not None:
            (Path(d) / ".gstack").mkdir()
            (Path(d) / ".gstack" / "e2e-executor").write_text(pin + "\n")
        p = subprocess.run(["bash", str(HYGIENE)], cwd=d, capture_output=True, text=True)
        assert p.returncode == 0, why
        assert p.stdout == "", f"{why}: printed {p.stdout!r}"


def test_vm_hygiene_never_stops_a_vm():
    """The rig's rule: no automation stops a guest, because a VM you did not start may
    be someone else's run. Report only."""
    text = HYGIENE.read_text()
    assert "Reports, never acts" in text
    assert not re.search(r"^\s*(vm-stop|kill|pkill)\s", text, re.M), \
        "the hook must not stop anything — only name what it found"


