import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
ROUTE = (REPO / "skills" / "e2e-route" / "SKILL.md").read_text()
RUNNER = (REPO / "skills" / "e2e-scaffold" / "templates" / "run-uitests.sh").read_text()
XCODE_BLOCK = (REPO / "skills" / "setup-routing" / "blocks" / "xcode-tools.md").read_text()
PLACEHOLDERS = (REPO / "skills" / "setup-routing" / "blocks" / "PLACEHOLDERS.md").read_text()
ADAPT = (REPO / "skills" / "adapt" / "SKILL.md").read_text()
SETUP = (REPO / "skills" / "setup-routing" / "SKILL.md").read_text()
HYGIENE = REPO / "scripts" / "vm-hygiene.sh"


def runner_template() -> str:
    """The generated scripts/run-uitests.sh, as the scaffold skill ships it.

    The template is its own file (not a fenced block in SKILL.md), so it is read whole.
    The header is the unversioned `# Auto-generated by /e2e-scaffold`; the SPM-only stub
    in SKILL.md shares that prefix but lives in the prose, not here.
    """
    assert RUNNER.startswith("#!/usr/bin/env bash\n# Auto-generated by /e2e-scaffold\n"), \
        "the runner header must be the literal, unversioned banner"
    return RUNNER


def flat(text: str) -> str:
    """Whitespace-collapsed, so an assertion does not depend on where prose wrapped."""
    return " ".join(text.split())


