"""Guard the `.gstack/e2e-executor` axis — the one pin that can lie quietly.

Every other failure in this feature announces itself: a VM that will not boot, a rig
that is not installed, a test that fails. The dangerous one is a run that looks
completely normal while executing somewhere the user did not choose — a `VM` typo
degrading to host, or every test skipped and exit 0.

So these tests hold three properties: the pin is validated rather than coerced, an
absent rig and a failing rig get opposite treatment, and `executed` is always visible.
They assert on SKILL.md prose the way test_spec_drift_skill.py does, because these
contracts live in text an agent reads, plus real behaviour for the shell that ships.
"""
from __future__ import annotations

import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[2]
ROUTE = (REPO / "skills" / "e2e-route" / "SKILL.md").read_text()
SCAFFOLD = (REPO / "skills" / "macos-e2e-scaffold" / "SKILL.md").read_text()
XCODE_BLOCK = (REPO / "skills" / "setup-routing" / "blocks" / "xcode-tools.md").read_text()
PLACEHOLDERS = (REPO / "skills" / "setup-routing" / "blocks" / "PLACEHOLDERS.md").read_text()
ADAPT = (REPO / "skills" / "adapt" / "SKILL.md").read_text()
SETUP = (REPO / "skills" / "setup-routing" / "SKILL.md").read_text()
HYGIENE = REPO / "scripts" / "vm-hygiene.sh"


def runner_template() -> str:
    """The generated scripts/run-uitests.sh, as it sits in the scaffold skill.

    Anchor on the VERSIONED banner: the SPM-only stub earlier in the file starts with
    the same unversioned prefix, and matching that returns a four-line refusal instead
    of the runner — every assertion below would then pass or fail for the wrong reason.
    """
    start = SCAFFOLD.index("# Auto-generated by /macos-e2e-scaffold v")
    return SCAFFOLD[start:SCAFFOLD.index("```", start)]


def flat(text: str) -> str:
    """Whitespace-collapsed, so an assertion does not depend on where prose wrapped."""
    return " ".join(text.split())


# --- the pin is validated, never coerced ------------------------------------------

# Explicit ids: the parameters here are whole SKILL.md files, and pytest would otherwise
# derive multi-thousand-character node ids from them, put those in PYTEST_CURRENT_TEST,
# and hand every spawned subprocess an oversized environment — E2BIG on Linux, fine on
# macOS. That is the 2.52.1 bug; test_node_id_budget.py caught this very test.
@pytest.mark.parametrize("surface,text", [
    pytest.param("runner template", runner_template(), id="runner-template"),
    pytest.param("e2e-route", ROUTE, id="e2e-route"),
    pytest.param("xcode-tools block", XCODE_BLOCK, id="xcode-tools-block"),
    pytest.param("PLACEHOLDERS", PLACEHOLDERS, id="placeholders"),
])
def test_an_invalid_pin_is_refused_not_treated_as_host(surface, text):
    """`VM`, a trailing space or a stray comment must not degrade to host. Coercing an
    unrecognised value is indistinguishable from success at the point it matters."""
    assert "BLOCKED — invalid .gstack/e2e-executor" in flat(text), surface


def test_absence_of_the_file_means_host_everywhere():
    """The default is defined, not incidental — a project that never opts in must read
    correctly rather than hit an error path."""
    for surface, text in (("route", ROUTE), ("block", XCODE_BLOCK), ("placeholders", PLACEHOLDERS)):
        assert re.search(r"absen\w+ (of the file )?means?\s+`?host`?|file's absence means", text), surface


# --- absent rig and failing rig are opposites -------------------------------------

def test_missing_rig_falls_back_loudly():
    template = runner_template()
    assert "rig not found on this host — running on host without lease" in template
    assert "rig not found on this host — running on host without lease" in ROUTE, \
        "the route's decision block must carry the same wording the runner prints"


def test_a_failing_rig_does_not_fall_back():
    """The distinction the whole design turns on: a rig FAULT is the thing to surface.
    Running on the host instead converts a real defect into a silently slower pass."""
    template = runner_template()
    assert "E2E RIG FAILED" in template
    assert "Not falling back to the host" in template
    fault = template.index("E2E RIG FAILED")
    fallback = template.index("rig not found on this host")
    assert fault < fallback, "fault handling must come before the absent-rig fallback"


def test_non_interactive_session_refuses_the_fallback():
    """The fallback is only safe because a human reads the warning. In CI nobody does,
    and an unleased host run can collide with another."""
    template = runner_template()
    assert "CI:-" in template and "GITHUB_ACTIONS:-" in template
    assert "Refusing in a non-interactive session" in template
    assert "non-interactive" in ROUTE


# --- "green and empty" is a failure, not a pass -----------------------------------

def test_executed_is_derived_and_zero_is_a_failure():
    """Every test skipped, nothing run, exit 0 reads as success. `executed` is the number
    that says whether anything happened — and it is DERIVED from the two validated
    counts, never read from the rig, so a malformed field cannot reach the comparison.
    (Round 3 tightened this: the earlier `.executed // …` fallback trusted the rig's own
    value when it was present, which is the surface this removes.)"""
    template = runner_template()
    assert "green and empty is not a pass" in template
    assert "0 tests executed" in template
    assert "SKIPPED ))" in template, "executed must be computed from total and skipped"
    assert "skipped=" in template, "skipped must be printed in plain text on every run"


def test_the_block_tells_the_reader_to_treat_zero_executed_as_failure():
    assert "executed == 0" in XCODE_BLOCK
    assert "Green and empty" in XCODE_BLOCK


